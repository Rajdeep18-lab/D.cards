// Quick index caches
const branchIdIndex = new Map();
const ifscIndex = new Map();

BRANCHES.forEach(branch => {
  if (branch.branchId) {
    branchIdIndex.set(branch.branchId.toLowerCase(), branch);
  }
  if (branch.ifsc) {
    ifscIndex.set(branch.ifsc.toUpperCase(), branch);
  }
});

/**
 * Get branch by its branchId
 * @param {string} branchId 
 * @returns {Object|null}
 */
export function getBranchById(branchId) {
  if (!branchId) return null;
  return branchIdIndex.get(String(branchId).trim().toLowerCase()) || null;
}

/**
 * Get branch by official IFSC code
 * @param {string} ifsc 
 * @returns {Object|null}
 */
export function getBranchByIFSC(ifsc) {
  if (!ifsc) return null;
  return ifscIndex.get(String(ifsc).trim().toUpperCase()) || null;
}
